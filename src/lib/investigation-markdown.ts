import type { IssueAnalysisResult } from "@/lib/issue-analysis-schema";

type MarkdownInvestigation = {
  repository: {
    owner: string;
    name: string;
  };
  issue: {
    number: number;
    title: string;
    url: string;
  };
  result: IssueAnalysisResult;
  model: string;
};

export function buildInvestigationMarkdown(investigation: MarkdownInvestigation) {
  const { repository, issue, result, model } = investigation;

  return [
    `# ${issue.title}`,
    "",
    `- **Repository:** ${repository.owner}/${repository.name}`,
    `- **Issue:** [#${issue.number}](${issue.url})`,
    `- **Classification:** ${humanize(result.classification.category)} (${percent(result.classification.confidence)} confidence)`,
    `- **Severity:** ${humanize(result.severity.level)} (${percent(result.severity.confidence)} confidence)`,
    `- **Model:** ${model}`,
    "",
    "## Summary",
    "",
    result.summary,
    "",
    "## Classification",
    "",
    result.classification.rationale,
    "",
    "## Severity",
    "",
    result.severity.rationale,
    "",
    "## Missing information",
    "",
    ...sectionOrFallback(
      result.missingInformation.map((item) =>
        [
          `### ${humanize(item.category)} — ${humanize(item.status)}`,
          "",
          item.explanation,
          ...(item.followUpQuestion
            ? ["", `**Follow-up:** ${item.followUpQuestion}`]
            : []),
        ].join("\n"),
      ),
      "No missing-information findings were returned.",
    ),
    "",
    buildReproductionMarkdown(result),
    "",
    "## Duplicate candidates",
    "",
    ...sectionOrFallback(
      result.duplicateCandidates.map(
        (candidate) =>
          `- [#${candidate.issueNumber}: ${candidate.title}](${candidate.url}) — ${percent(candidate.similarity)} similarity. ${candidate.explanation}`,
      ),
      "No supported same-repository duplicate candidates were returned.",
    ),
    "",
    "## Probable causes",
    "",
    ...sectionOrFallback(
      result.probableCauses.map(
        (cause) =>
          `- **${cause.title}** (${percent(cause.confidence)} confidence): ${cause.explanation} Evidence: ${cause.evidenceIds.join(", ") || "none"}.`,
      ),
      "No evidence-backed probable causes were returned.",
    ),
    "",
    "## Evidence ledger",
    "",
    ...sectionOrFallback(
      result.evidence.map((item) =>
        [
          `### ${item.id} — ${humanize(item.source)}`,
          "",
          `**Reference:** ${item.reference}`,
          ...(item.excerpt ? ["", `> ${item.excerpt.replaceAll("\n", "\n> ")}`] : []),
          "",
          `**Supports:** ${item.supports}`,
        ].join("\n"),
      ),
      "No evidence items were returned.",
    ),
    "",
    buildFollowUpQuestionsMarkdown(result),
    "",
    "## Limitations",
    "",
    ...listOrFallback(result.limitations, "No limitations were returned."),
    "",
    "## Suggested labels",
    "",
    result.suggestedLabels.length
      ? result.suggestedLabels.map((label) => `\`${label}\``).join(" ")
      : "No labels were suggested.",
    "",
    "---",
    "Generated by IssueLens for human review. No GitHub changes were made.",
    "",
  ].join("\n");
}

export function buildReproductionMarkdown(result: IssueAnalysisResult) {
  return [
    "## Reproduction plan",
    "",
    `**Readiness:** ${humanize(result.reproduction.readiness)}`,
    "",
    "### Prerequisites",
    "",
    ...listOrFallback(result.reproduction.prerequisites, "No prerequisites were returned."),
    "",
    "### Steps",
    "",
    ...numberedListOrFallback(result.reproduction.steps, "No reproduction steps were returned."),
    "",
    "### Expected behavior",
    "",
    result.reproduction.expectedBehavior ?? "Not supplied.",
    "",
    "### Actual behavior",
    "",
    result.reproduction.actualBehavior ?? "Not supplied.",
    "",
    "### Notes",
    "",
    ...listOrFallback(result.reproduction.notes, "No reproduction notes were returned."),
  ].join("\n");
}

export function buildFollowUpQuestionsMarkdown(result: IssueAnalysisResult) {
  return [
    "## Follow-up questions",
    "",
    ...numberedListOrFallback(result.followUpQuestions, "No follow-up questions were returned."),
  ].join("\n");
}

export function investigationMarkdownFilename(
  repository: MarkdownInvestigation["repository"],
  issueNumber: number,
) {
  const repositoryName = `${repository.owner}-${repository.name}`
    .replace(/[^a-z0-9-]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();

  return `${repositoryName || "github-issue"}-issue-${issueNumber}-triage.md`;
}

function sectionOrFallback(items: string[], fallback: string) {
  return items.length ? items.flatMap((item, index) => (index ? ["", item] : [item])) : [fallback];
}

function listOrFallback(items: string[], fallback: string) {
  return items.length ? items.map((item) => `- ${item}`) : [fallback];
}

function numberedListOrFallback(items: string[], fallback: string) {
  return items.length ? items.map((item, index) => `${index + 1}. ${item}`) : [fallback];
}

function humanize(value: string) {
  return value.replaceAll("_", " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function percent(value: number) {
  return `${Math.round(value * 100)}%`;
}
